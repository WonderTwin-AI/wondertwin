//go:build ignore

// gen_request_schema writes request_schema_gen.go: for each route in
// router.go that the pinned dahlia GA spec documents, the top-level
// parameters it accepts and the parameters that take an integer.
//
// It reads the same spec as gen_response_schema.go, which says how to restore
// it; the go:generate directive in request_validation.go passes that path as
// $STRIPE_SPEC. It runs from this directory:
//
//	go run gen_request_schema.go -spec /path/to/stripe-v1-2026-08-26.dahlia.json
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

const specID = "openapi-v1-2026-08-26.dahlia"

type schema struct {
	Ref         string             `json:"$ref"`
	Type        string             `json:"type"`
	Description string             `json:"description"`
	Properties  map[string]*schema `json:"properties"`
	Items       *schema            `json:"items"`
	AnyOf       []*schema          `json:"anyOf"`
}

type operation struct {
	Parameters []struct {
		Name   string  `json:"name"`
		In     string  `json:"in"`
		Schema *schema `json:"schema"`
	} `json:"parameters"`
	RequestBody struct {
		Content map[string]struct {
			Schema *schema `json:"schema"`
		} `json:"content"`
	} `json:"requestBody"`
}

var schemas map[string]*schema

func resolve(s *schema) *schema {
	for s != nil && s.Ref != "" {
		s = schemas[strings.TrimPrefix(s.Ref, "#/components/schemas/")]
	}
	return s
}

// Integer kinds, matching the constants in request_validation.go.
const (
	intAny = iota + 1
	intUnsigned
)

// intKind reads whether the spec describes an integer as positive or
// non-negative; it has no minimum keyword.
func intKind(s *schema) int {
	d := strings.ToLower(s.Description)
	if strings.Contains(d, "positive integer") || strings.Contains(d, "non-negative integer") {
		return intUnsigned
	}
	return intAny
}

// integers records every parameter path under s that takes an integer, with
// array indexes written as [].
func integers(prefix string, s *schema, depth int, out map[string]int) {
	s = resolve(s)
	if s == nil || depth > 5 {
		return
	}
	alts := []*schema{s}
	if len(s.AnyOf) > 0 {
		alts = s.AnyOf
	}
	for _, a := range alts {
		a = resolve(a)
		if a == nil {
			continue
		}
		switch {
		case a.Type == "integer":
			if prefix != "" {
				k := intKind(a)
				if k == intAny {
					k = intKind(s)
				}
				out[prefix] = k
			}
		case a.Type == "array" && a.Items != nil:
			integers(prefix+"[]", a.Items, depth+1, out)
		case len(a.Properties) > 0:
			for name, p := range a.Properties {
				key := name
				if prefix != "" {
					key = prefix + "[" + name + "]"
				}
				integers(key, p, depth+1, out)
			}
		}
	}
}

var routeRE = regexp.MustCompile(`r\.(Get|Post|Delete)\("([^"]+)"`)
var paramRE = regexp.MustCompile(`\{[^}]+\}`)

func main() {
	specPath := flag.String("spec", "", "path to the pinned Stripe OpenAPI spec")
	out := flag.String("o", "request_schema_gen.go", "output file")
	flag.Parse()
	raw, err := os.ReadFile(*specPath)
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(raw)
	var sp struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas map[string]*schema `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(raw, &sp); err != nil {
		log.Fatal(err)
	}
	schemas = sp.Components.Schemas

	specOps := map[string]operation{}
	for path, ops := range sp.Paths {
		for method, rawOp := range ops {
			var op operation
			if json.Unmarshal(rawOp, &op) != nil {
				continue
			}
			specOps[strings.ToUpper(method)+" "+paramRE.ReplaceAllString(path, "{}")] = op
		}
	}

	router, err := os.ReadFile("router.go")
	if err != nil {
		log.Fatal(err)
	}
	type entry struct {
		params   []string
		integers map[string]int
	}
	routes := map[string]entry{}
	for _, m := range routeRE.FindAllStringSubmatch(string(router), -1) {
		key := strings.ToUpper(m[1]) + " /v1" + paramRE.ReplaceAllString(m[2], "{}")
		op, ok := specOps[key]
		if !ok {
			continue
		}
		if _, form := op.RequestBody.Content["application/x-www-form-urlencoded"]; len(op.RequestBody.Content) > 0 && !form {
			continue // a multipart upload (files); its parts are not checked
		}
		e := entry{integers: map[string]int{}}
		names := map[string]bool{}
		if body := op.RequestBody.Content["application/x-www-form-urlencoded"].Schema; body != nil {
			for name := range resolve(body).Properties {
				names[name] = true
			}
			integers("", body, 0, e.integers)
		}
		for _, p := range op.Parameters {
			if p.In != "query" {
				continue
			}
			names[p.Name] = true
			integers(p.Name, p.Schema, 1, e.integers)
		}
		for n := range names {
			e.params = append(e.params, n)
		}
		sort.Strings(e.params)
		routes[key] = e
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_request_schema.go from %s (sha256 %s). DO NOT EDIT.\n\n", specID, hex.EncodeToString(sum[:]))
	b.WriteString("package api\n\n")
	b.WriteString("// requestSchemas lists, per route the spec documents, the top-level\n// parameters it accepts and the parameter paths that take an integer.\n")
	b.WriteString("var requestSchemas = map[string]requestSchema{\n")
	kinds := map[int]string{intAny: "intAny", intUnsigned: "intUnsigned"}
	keys := make([]string, 0, len(routes))
	for k := range routes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		e := routes[k]
		fmt.Fprintf(&b, "%q: {\nparams: setOf(%s),\n", k, quoteAll(e.params))
		if len(e.integers) > 0 {
			b.WriteString("integers: map[string]int{\n")
			ik := make([]string, 0, len(e.integers))
			for p := range e.integers {
				ik = append(ik, p)
			}
			sort.Strings(ik)
			for _, p := range ik {
				fmt.Fprintf(&b, "%q: %s,\n", p, kinds[e.integers[p]])
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func quoteAll(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(q, ", ")
}
